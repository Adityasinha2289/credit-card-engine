/**
 * Generates supabase/migrations/20261017000100_card_catalog.sql from the same
 * card dataset the app uses (MASTER_CARD_DATASET), so user_cards.card_id can
 * always reference a real catalog row.
 *
 *   npx tsx scripts/generate-card-seed.ts
 *
 * Re-run (and re-apply via a new migration) whenever the dataset changes.
 */
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MASTER_CARD_DATASET } from '../src/features/finix/data/masterDataset';

const out = resolve(dirname(fileURLToPath(import.meta.url)), '../supabase/migrations/20261017000100_card_catalog.sql');

const rows = MASTER_CARD_DATASET.map((c) => ({
  id: c.id,
  name: c.name,
  bank: c.bank,
  network: c.network,
  annual_fee: c.annualFee,
  fee_waiver_spend: c.feeWaiverSpend ?? null,
  // 0 in the dataset means "not published"
  min_income: c.minIncome > 0 ? c.minIncome : null,
  min_cibil: c.minCibil > 0 ? c.minCibil : null,
  welcome_bonus: c.welcomeBonus ?? null,
  lounge_access: c.loungeAccess ?? 0,
  base_reward_rate: c.baseRewardRate,
  rewards: c.rewards ?? [],
  highlights: c.highlights ?? [],
  gradient_from: c.gradientFrom ?? null,
  gradient_to: c.gradientTo ?? null,
}));

const json = JSON.stringify(rows);
if (json.includes('$cards$')) throw new Error('Dollar-quote tag collision');

const sql = `-- =============================================================================
--  Card catalog seed — GENERATED by scripts/generate-card-seed.ts. Do not edit.
--  Source: src/features/finix/data/masterDataset.ts (${rows.length} cards)
-- =============================================================================

INSERT INTO public.cards (
  id, name, bank, network, annual_fee, fee_waiver_spend, min_income, min_cibil,
  welcome_bonus, lounge_access, base_reward_rate, rewards, highlights, gradient_from, gradient_to
)
SELECT id, name, bank, network, annual_fee, fee_waiver_spend, min_income, min_cibil,
       welcome_bonus, COALESCE(lounge_access, 0), base_reward_rate,
       COALESCE(rewards, '[]'::jsonb), COALESCE(highlights, '[]'::jsonb), gradient_from, gradient_to
FROM jsonb_to_recordset($cards$${json}$cards$::jsonb) AS x(
  id TEXT, name TEXT, bank TEXT, network TEXT, annual_fee INTEGER, fee_waiver_spend INTEGER,
  min_income INTEGER, min_cibil INTEGER, welcome_bonus TEXT, lounge_access INTEGER,
  base_reward_rate NUMERIC, rewards JSONB, highlights JSONB, gradient_from TEXT, gradient_to TEXT
)
ON CONFLICT (id) DO UPDATE SET
  name = EXCLUDED.name, bank = EXCLUDED.bank, network = EXCLUDED.network,
  annual_fee = EXCLUDED.annual_fee, fee_waiver_spend = EXCLUDED.fee_waiver_spend,
  min_income = EXCLUDED.min_income, min_cibil = EXCLUDED.min_cibil,
  welcome_bonus = EXCLUDED.welcome_bonus, lounge_access = EXCLUDED.lounge_access,
  base_reward_rate = EXCLUDED.base_reward_rate, rewards = EXCLUDED.rewards,
  highlights = EXCLUDED.highlights, gradient_from = EXCLUDED.gradient_from,
  gradient_to = EXCLUDED.gradient_to;
`;

writeFileSync(out, sql);
console.log(`Wrote ${rows.length} cards to ${out}`);
